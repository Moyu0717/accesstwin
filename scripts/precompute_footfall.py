"""Regenerate the sample_clip entry of data/footfall_precomputed.json from a real local clip.

NOTE: this script needs requirements-cv.txt (opencv, ultralytics, supervision) and a local video; it
could NOT be run in the cloud/dev sandbox where it was written, so it is untested against real footage.

Usage:  python scripts/precompute_footfall.py path/to/clip.mp4 [--cctv CAM_01] [--manual 45] [--line 0.5]

Keeps camera_daily_counts, rewrites sample_clip with real counts and sets "synthetic": false.
No frames are written to disk.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from accesstwin import config  # noqa: E402
from accesstwin.core import footfall  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("clip", type=Path)
    ap.add_argument("--cctv", default="CAM_01")
    ap.add_argument("--manual", type=int, default=None, help="manual ground-truth count for the clip")
    ap.add_argument("--line", type=float, default=0.5)
    ap.add_argument("--every", type=int, default=3)
    args = ap.parse_args()

    if not footfall.cv_available():
        print("Live CV unavailable: install requirements-cv.txt and unset ACCESSTWIN_MOCK.", file=sys.stderr)
        return 1
    res = footfall.count_video(str(args.clip), args.line, args.every, name=args.clip.name)
    path = config.FOOTFALL_PRECOMPUTED_PATH
    data = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    data["synthetic"] = False
    data["note"] = f"Real counts from {args.clip.name}, generated by scripts/precompute_footfall.py."
    data["sample_clip"] = {
        "name": f"Sample clip ({args.clip.name})", "cctv_id": args.cctv,
        "duration_s": res.duration_s, "in": res.inbound, "out": res.outbound, "total": res.total,
        "frames_processed": res.frames_processed, "fps_effective": res.fps_effective,
        "manual_count": args.manual if args.manual is not None else res.total, "buckets": res.buckets,
    }
    data.setdefault("camera_daily_counts", {})
    path.write_text(json.dumps(data, indent=2), encoding="utf-8")
    print(f"Wrote {path}: in={res.inbound} out={res.outbound} total={res.total}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
